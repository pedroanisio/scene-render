#!/usr/bin/env python3
"""Writes CHANGELOG.md from the RELEASE_NOTES.md of every release tag.

usage: tools/changelog.py           rewrite CHANGELOG.md
       tools/changelog.py --check   exit 1 when CHANGELOG.md differs from what would be written

RELEASE_NOTES.md holds the notes of one release and is rewritten for the next. This keeps every earlier release's
notes: one entry per tag vMAJOR.MINOR.PATCH, newest first, each the RELEASE_NOTES.md of that tag with its headings
one level down. When the working tree's RELEASE_NOTES.md names a version that has no tag yet, it is the first entry.
Releases up to v0.4.1 were tagged in the previous repository (github.com/pedroanisio/rs-scene-render, MIT); their
entries are kept as released in tools/changelog-history.md and follow the tagged entries.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HISTORY = ROOT / "tools" / "changelog-history.md"
TAG = re.compile(r"^v(\d+)\.(\d+)\.(\d+)$")
TITLE = re.compile(r"^# scene-render (v\d+\.\d+\.\d+)\s*$")

HEADER = """# Changelog

The release notes of every tagged release, newest first. Generated by `tools/changelog.py` from `RELEASE_NOTES.md`
at each tag; edit `RELEASE_NOTES.md`, not this file. Entries are kept as released, so a document they cite may have
been removed since: "the cinematic impact SREP" is sr-core SREP 40, whose working draft this repository removed after v0.3.2.
Versions up to v0.4.1 were released under the MIT License from github.com/pedroanisio/rs-scene-render.
"""


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def entry(notes, date):
    """Returns (version, entry text) for release notes whose first line is '# scene-render vX.Y.Z'."""
    lines = notes.strip("\n").splitlines()
    m = TITLE.match(lines[0]) if lines else None
    if not m:
        raise ValueError(f"release notes must start with '# scene-render vX.Y.Z', got {lines[:1]}")
    body = ["#" + line if line.startswith("#") else line for line in lines[1:]]
    return m.group(1), "\n".join([f"## {m.group(1)} — {date}", *body]).rstrip() + "\n"


def tagged_entries():
    tags = [t for t in git("tag", "--list", "v*").split() if TAG.match(t)]
    tags.sort(key=lambda t: tuple(int(x) for x in TAG.match(t).groups()), reverse=True)
    out = []
    for tag in tags:
        notes = git("show", f"{tag}:RELEASE_NOTES.md")
        version, text = entry(notes, git("log", "-1", "--format=%as", tag).strip())
        if version != tag:
            raise ValueError(f"{tag}: RELEASE_NOTES.md is titled {version}")
        out.append((version, text))
    return out


def render():
    entries = tagged_entries()
    current, text = entry((ROOT / "RELEASE_NOTES.md").read_text(), "unreleased")
    if current not in {v for v, _ in entries}:
        entries.insert(0, (current, text))
    history = HISTORY.read_text() if HISTORY.exists() else ""
    return HEADER + "".join("\n" + t for _, t in entries) + ("\n" + history if history else "")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    text = render()
    path = ROOT / "CHANGELOG.md"
    if args.check:
        if not path.exists() or path.read_text() != text:
            print("CHANGELOG.md is out of date; run tools/changelog.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
