//! Authored delivery metadata. No value is derived from the current date or time.
use sr_model::model as m;

/// The narration track selected for the described version of the programme.
pub(crate) fn description(scene: &m::Scene) -> Option<&str> {
    scene.metadata.as_ref()?.children.iter().find_map(|c| match c {
        m::MetadataChild::Accessibility(a) => a.audio_description.as_deref(),
        _ => None,
    })
}

/// Caption identity in the delivery manifest and render report.
#[derive(Debug, Clone, PartialEq, serde::Serialize)]
pub struct CaptionInfo {
    pub id: String,
    pub language: String,
    pub label: Option<String>,
    pub kind: String,
}
impl From<&m::CaptionTrack> for CaptionInfo {
    fn from(t: &m::CaptionTrack) -> Self {
        Self { id: t.id.clone(), language: t.language.to_string(), label: t.label.clone(), kind: t.kind.to_string() }
    }
}

/// The one language of a mix, `mul` for several declared languages, or `und` if unspecified.
/// Music/effects without a language do not erase the language of a declared voice track.
pub(crate) fn audio_language(
    p: &sr_eval::Program,
    output: &m::Output,
    description: Option<(&str, bool)>,
    wanted: Option<&str>,
    warnings: &mut Vec<String>,
) -> String {
    let tracks = p
        .scene
        .audio_mix
        .iter()
        .flat_map(|am| &am.children)
        .filter_map(|c| match c {
            m::AudioMixChild::AudioTrack(t) => Some((t, true)),
            _ => None,
        })
        .chain(output.children.iter().filter_map(|c| match c {
            m::OutputChild::AudioTrack(t) => Some((t, false)),
            _ => None,
        }));
    let segmented = output.children.iter().any(|c| matches!(c, m::OutputChild::Segment(_)));
    let mut codes = std::collections::BTreeSet::new();
    for (t, composition) in tracks {
        if t.mute || !crate::audio_language::audible_bus(p, t.bus.as_deref()) {
            continue;
        }
        let selected = if let Some((_, include)) = description.filter(|(id, _)| *id == t.id) {
            include
        } else {
            !composition || !segmented || crate::segment_audio::track_selected(p, output, &t.id)
        };
        if !selected {
            continue;
        }
        let tag = t.language.as_ref().map(|l| l.to_string());
        if let Some(tag) = tag.or_else(|| crate::audio_language::asset_language(p, &t.asset, wanted)) {
            let code = language_code(&tag).unwrap_or_else(|| {
                warnings.push(format!(
                    "audio track {}: language {tag:?} has no ISO 639-2 mapping; using und for this track",
                    t.id
                ));
                "und"
            });
            codes.insert(code);
        }
    }
    for tag in crate::audio_language::layer_languages(p, output, wanted) {
        let code = language_code(&tag).unwrap_or_else(|| {
            warnings.push(format!("video audio: language {tag:?} has no ISO 639-2 mapping; using und for it"));
            "und"
        });
        codes.insert(code);
    }
    if codes.len() > 1 {
        "mul".into()
    } else {
        codes.into_iter().next().unwrap_or("und").into()
    }
}

/// BCP-47 primary language to ISO 639-2/T. Region/script remain in the authored document.
fn language_code(tag: &str) -> Option<&'static str> {
    let primary = tag.split('-').next()?.to_ascii_lowercase();
    ISO_639.iter().find(|(key, _)| *key == primary).map(|(_, value)| *value)
}

